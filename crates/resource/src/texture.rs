use std::any::Any;
use vyxen_math::{Random, Vector2};

use crate::Resource;

/// Texture/Image type
///
/// # Examples
/// ## Raw bytes
/// ```rust, ignore
/// use vyxen_resource::{Texture, load_bytes};
///
/// let bytes = include_bytes!("test-img.png");
///
/// let texture = load_bytes::<Texture>(bytes).unwrap();
/// ```
/// ## Path
/// ```rust, ignore
/// use vyxen_resource::{Texture, load_path};
///
/// let texture = load_path::<Texture>("test-img.png").unwrap();
/// ```
#[derive(Debug, Clone, PartialEq)]
pub struct Texture {
    id: u64,
    dim: Vector2,
    rgba: Vec<u8>,
}

impl Resource for Texture {
    fn load(data: &[u8]) -> anyhow::Result<Self> {
        let id = Random::from_time().next_u64();

        let image = image::load_from_memory(data)?;
        let dim = Vector2 {
            x: image.width() as f32,
            y: image.height() as f32,
        };
        let rgba = image.into_rgba8().into_raw();

        Ok(Self { id, dim, rgba })
    }

    fn as_any(&self) -> &dyn Any {
        self
    }
}

impl Texture {
    /// Returns the texture's ID.
    pub fn get_id(&self) -> u64 {
        self.id
    }

    /// Returns the texture's dimensions.
    pub fn get_dimensions(&self) -> Vector2 {
        self.dim
    }

    /// Returns the texture's RGBA data.
    pub fn get_rgba(&self) -> &[u8] {
        &self.rgba
    }
}

